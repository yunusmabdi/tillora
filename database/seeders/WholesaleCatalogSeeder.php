            ['SAFETY', 'Safety & Protective Equipment', 'PPE and workplace safety equipment sold in bulk packs.'],
            ['GENERAL', 'General Business Supplies', 'Miscellaneous equipment and consumables for shops and offices.'],
        ];

        $map = [];

        foreach ($definitions as [$code, $name, $description]) {
            $category = Category::query()->where('code', $code)
                ->orWhere('name', $name)
                ->first();

            if ($category) {
                $category->update([
                    'code' => $code,
                    'name' => $name,
                    'slug' => \Illuminate\Support\Str::slug($name),
                    'description' => $description,
                    'is_active' => true,
                ]);
            } else {
                $category = Category::create([
                    'code' => $code,
                    'name' => $name,
                    'slug' => \Illuminate\Support\Str::slug($name),
                    'description' => $description,
                    'is_active' => true,
                ]);
            }

            $map[$code] = $category->id;
        }

        return $map;
    }

