/**
 * WholesaleCatalogSeeder
 *
 * Seeds Tillora with a realistic Kenyan B2B wholesale demo catalog:
 * categories, suppliers, products, purchases, purchase items and
 * stock movements. Safe to re-run — uses updateOrCreate/firstOrCreate
 * throughout and never truncates or wipes existing data.
 *
 * Run with: php artisan db:seed --class=WholesaleCatalogSeeder
 */
class WholesaleCatalogSeeder extends Seeder
{
    public function run(): void
    {
        DB::transaction(function () {
            $categories = $this->seedCategories();
            $suppliers  = $this->seedSuppliers();
            $products   = $this->seedProducts($categories);
            $this->seedPurchases($suppliers, $products);
            $this->seedOutMovements($products);
        });

        $this->command?->info('Wholesale catalog seeded successfully.');
    }

